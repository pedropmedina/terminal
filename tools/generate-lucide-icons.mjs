import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import javaPlugin from "prettier-plugin-java";
import * as selectedIcons from "./lucide-icons.mjs";

const outputUrl = new URL("../app/src/main/java/com/acteque/terminal/ui/icons/LucideIcons.java", import.meta.url);
const allowedAttributes = {
  path: new Set(["d", "key"]),
  line: new Set(["x1", "y1", "x2", "y2", "key"]),
  circle: new Set(["cx", "cy", "r", "key"]),
  ellipse: new Set(["cx", "cy", "rx", "ry", "key"]),
  rect: new Set(["x", "y", "width", "height", "rx", "ry", "key"]),
  polyline: new Set(["points", "key"]),
  polygon: new Set(["points", "key"]),
};
const checkOnly = process.argv.includes("--check");
const projectPackage = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const lucideVersion = projectPackage.devDependencies?.["@lucide/icons"];
if (!lucideVersion || !/^\d+\.\d+\.\d+$/.test(lucideVersion)) {
  throw new Error("@lucide/icons must be an exact pinned development dependency");
}

const output = await format(generateCatalog(selectedIcons, lucideVersion), {
  parser: "java",
  plugins: [javaPlugin],
});

if (checkOnly) {
  let current;
  try {
    current = await readFile(outputUrl, "utf8");
  } catch {
    fail(`Missing generated icon catalog: ${fileURLToPath(outputUrl)}`);
  }
  if (current !== output) {
    fail("LucideIcons.java is stale. Run `npm run generate-icons`.");
  }
} else {
  await writeFile(outputUrl, output, "utf8");
}

function generateCatalog(icons, version) {
  const constants = Object.entries(icons)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([exportName, icon]) => generateConstant(exportName, icon))
    .join(",\n\n");

  return (
    `// Generated by tools/generate-lucide-icons.mjs from @lucide/icons ${version}. Do not edit.\n` +
    `package com.acteque.terminal.ui.icons;\n\n` +
    `/** Lucide icon geometry included in the application. */\n` +
    `public enum LucideIcons implements LucideGlyph {\n` +
    `${indent(constants, 2)};\n\n` +
    `  private final String sourceName;\n` +
    `  private final double width;\n` +
    `  private final double height;\n` +
    `  private final String pathData;\n\n` +
    `  LucideIcons(String sourceName, double width, double height, String pathData) {\n` +
    `    this.sourceName = sourceName;\n` +
    `    this.width = width;\n` +
    `    this.height = height;\n` +
    `    this.pathData = pathData;\n` +
    `  }\n\n` +
    `  @Override\n` +
    `  public String sourceName() {\n` +
    `    return sourceName;\n` +
    `  }\n\n` +
    `  @Override\n` +
    `  public double width() {\n` +
    `    return width;\n` +
    `  }\n\n` +
    `  @Override\n` +
    `  public double height() {\n` +
    `    return height;\n` +
    `  }\n\n` +
    `  @Override\n` +
    `  public String pathData() {\n` +
    `    return pathData;\n` +
    `  }\n` +
    `}\n`
  );
}

function generateConstant(exportName, icon) {
  const width = icon.size ?? icon.width;
  const height = icon.size ?? icon.height;
  if (!icon.name || !positive(width) || !positive(height) || !Array.isArray(icon.node)) {
    throw new Error(`Invalid Lucide icon data for ${exportName}`);
  }

  const pathData = icon.node.map(([tag, attributes]) => toPathData(tag, attributes)).join(" ");
  const constantName = exportName
    .replace(/([a-z\d])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z\d]+/g, "_")
    .toUpperCase();

  return (
    `${constantName}(\n` +
    `  ${javaString(icon.name)},\n` +
    `  ${formatNumber(width)},\n` +
    `  ${formatNumber(height)},\n` +
    `  ${javaString(pathData)}\n` +
    `)`
  );
}

function toPathData(tag, attributes) {
  validateAttributes(tag, attributes);
  switch (tag) {
    case "path":
      // Each SVG child path starts with its current point at the view-box origin. Reset it here
      // so a leading relative command is not affected by the preceding child path.
      return `M0 0${requiredString(attributes, "d", tag)}`;
    case "line":
      return (
        `M${coordinate(attributes, "x1", tag)} ${coordinate(attributes, "y1", tag)}` +
        `L${coordinate(attributes, "x2", tag)} ${coordinate(attributes, "y2", tag)}`
      );
    case "circle": {
      const cx = coordinate(attributes, "cx", tag);
      const cy = coordinate(attributes, "cy", tag);
      const radius = coordinate(attributes, "r", tag);
      if (!positive(radius)) throw new Error("circle radius must be positive");
      return ellipsePath(cx, cy, radius, radius);
    }
    case "ellipse": {
      const cx = coordinate(attributes, "cx", tag);
      const cy = coordinate(attributes, "cy", tag);
      const rx = coordinate(attributes, "rx", tag);
      const ry = coordinate(attributes, "ry", tag);
      if (!positive(rx) || !positive(ry)) throw new Error("ellipse radii must be positive");
      return ellipsePath(cx, cy, rx, ry);
    }
    case "rect":
      return rectanglePath(attributes);
    case "polyline":
      return pointsPath(requiredString(attributes, "points", tag), false);
    case "polygon":
      return pointsPath(requiredString(attributes, "points", tag), true);
    default:
      throw new Error(`Unsupported Lucide element: ${tag}`);
  }
}

function validateAttributes(tag, attributes) {
  const allowed = allowedAttributes[tag];
  if (!allowed) throw new Error(`Unsupported Lucide element: ${tag}`);
  for (const attribute of Object.keys(attributes)) {
    if (!allowed.has(attribute)) {
      throw new Error(`Unsupported attribute '${attribute}' on Lucide ${tag}`);
    }
  }
}

function ellipsePath(cx, cy, rx, ry) {
  const left = formatNumber(cx - rx);
  const right = formatNumber(cx + rx);
  return (
    `M${left} ${formatNumber(cy)}` +
    `A${formatNumber(rx)} ${formatNumber(ry)} 0 1 0 ${right} ${formatNumber(cy)}` +
    `A${formatNumber(rx)} ${formatNumber(ry)} 0 1 0 ${left} ${formatNumber(cy)}`
  );
}

function rectanglePath(attributes) {
  const x = optionalCoordinate(attributes, "x", 0, "rect");
  const y = optionalCoordinate(attributes, "y", 0, "rect");
  const width = coordinate(attributes, "width", "rect");
  const height = coordinate(attributes, "height", "rect");
  if (!positive(width) || !positive(height)) throw new Error("rect dimensions must be positive");

  let rx = optionalCoordinate(attributes, "rx", Number.NaN, "rect");
  let ry = optionalCoordinate(attributes, "ry", Number.NaN, "rect");
  if (Number.isNaN(rx)) rx = Number.isNaN(ry) ? 0 : ry;
  if (Number.isNaN(ry)) ry = rx;
  if (rx < 0 || ry < 0) throw new Error("rect radii must not be negative");
  rx = Math.min(rx, width / 2);
  ry = Math.min(ry, height / 2);

  const right = x + width;
  const bottom = y + height;
  if (rx === 0 || ry === 0) {
    return (
      `M${formatNumber(x)} ${formatNumber(y)}H${formatNumber(right)}` + `V${formatNumber(bottom)}H${formatNumber(x)}Z`
    );
  }
  return (
    `M${formatNumber(x + rx)} ${formatNumber(y)}H${formatNumber(right - rx)}` +
    `A${formatNumber(rx)} ${formatNumber(ry)} 0 0 1 ${formatNumber(right)} ${formatNumber(y + ry)}` +
    `V${formatNumber(bottom - ry)}` +
    `A${formatNumber(rx)} ${formatNumber(ry)} 0 0 1 ${formatNumber(right - rx)} ${formatNumber(bottom)}` +
    `H${formatNumber(x + rx)}` +
    `A${formatNumber(rx)} ${formatNumber(ry)} 0 0 1 ${formatNumber(x)} ${formatNumber(bottom - ry)}` +
    `V${formatNumber(y + ry)}` +
    `A${formatNumber(rx)} ${formatNumber(ry)} 0 0 1 ${formatNumber(x + rx)} ${formatNumber(y)}Z`
  );
}

function pointsPath(points, close) {
  const values = points
    .trim()
    .split(/[\s,]+/)
    .map(Number);
  if (values.length < (close ? 6 : 4) || values.length % 2 !== 0 || values.some(notFinite)) {
    throw new Error(`Invalid ${close ? "polygon" : "polyline"} points: ${points}`);
  }
  let path = `M${formatNumber(values[0])} ${formatNumber(values[1])}`;
  for (let index = 2; index < values.length; index += 2) {
    path += `L${formatNumber(values[index])} ${formatNumber(values[index + 1])}`;
  }
  return close ? `${path}Z` : path;
}

function coordinate(attributes, name, tag) {
  if (!(name in attributes)) throw new Error(`Missing '${name}' on Lucide ${tag}`);
  return parsedNumber(attributes[name], `${tag}.${name}`);
}

function optionalCoordinate(attributes, name, fallback, tag) {
  return name in attributes ? parsedNumber(attributes[name], `${tag}.${name}`) : fallback;
}

function parsedNumber(value, label) {
  const result = Number(value);
  if (!Number.isFinite(result)) throw new Error(`Invalid number for ${label}: ${value}`);
  return result;
}

function requiredString(attributes, name, tag) {
  const value = attributes[name];
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`Missing '${name}' on Lucide ${tag}`);
  }
  return value;
}

function positive(value) {
  return Number.isFinite(value) && value > 0;
}

function notFinite(value) {
  return !Number.isFinite(value);
}

function formatNumber(value) {
  return Object.is(value, -0) ? "0" : String(value);
}

function javaString(value) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

function indent(value, spaces) {
  const prefix = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line) => prefix + line)
    .join("\n");
}

function fail(message) {
  console.error(message);
  process.exitCode = 1;
}
