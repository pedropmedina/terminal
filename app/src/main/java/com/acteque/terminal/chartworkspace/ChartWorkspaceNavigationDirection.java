package com.acteque.terminal.chartworkspace;

/** Cardinal directions used to navigate between chart panes. */
enum ChartWorkspaceNavigationDirection {
  /** Navigate to a pane left of the active chart. */
  LEFT,
  /** Navigate to a pane right of the active chart. */
  RIGHT,
  /** Navigate to a pane above the active chart. */
  ABOVE,
  /** Navigate to a pane below the active chart. */
  BELOW,
}
